// 모달에서 체력 측정 시작 버튼을 누른 후
export const speakIntro = (firstStep: FitnessStep) => {
  speak(STEP_SCRIPT[firstStep.label])
}

// 단계 변경 시
export const speakStepReady = (step: FitnessStep) => {
  speak(STEP_SCRIPT[step.label])
}

// 측정 시작 시
export const speakStepStart = (index: number, step: FitnessStep) => {
  speak(`${index + 1}단계 ${step.label} 측정을 시작합니다.`)
}

// 타이머 종료
export const speakStepComplete = () => {
  speak('측정이 완료되었습니다. 결과를 기록해 주세요.')
}
